/**
 * Regenerate the language packs from the code (local, deterministic).
 * Usage: npm run packs:build
 *
 * - locales/test.json         artificial TEST pack, every text "[TEST] …"
 * - locales/template.json     ewondo model to fill in: status draft, texts empty
 * - core/locale-test-pack.js  module copy of the TEST pack (loaded by Chrome)
 * - core/locale-ewo-pack.js   module copy of the ewondo pack currently shipped
 *                             (the draft model until install-ewo-pack is run)
 *
 * Existing translations in locales/template.json are kept: only missing
 * entries are added. Nothing is translated here.
 */
import { readFile, writeFile } from "node:fs/promises";
import { PACK_REQUIREMENTS } from "../core/language-pack.js";

const root = new URL("../", import.meta.url);
const readJson = async (path) => JSON.parse(await readFile(new URL(path, root), "utf8"));

export function moduleSource(exportName, pack, comment) {
  return `/**\n${comment.map((line) => ` * ${line}`).join("\n")}\n */\nexport const ${exportName} = Object.freeze(${JSON.stringify(pack, null, 2)});\n`;
}

function testText(requirement) {
  if (requirement.kind === "intent") return `[TEST] INTENTION ${requirement.id.replace(/[._]/gu, " ").toUpperCase()}`;
  if (requirement.kind === "fallback") {
    return requirement.id.endsWith("_warning")
      ? "[TEST] ATTENTION, MESSAGE NON RECONNU : VÉRIFIEZ AVANT DE CONTINUER"
      : "[TEST] MESSAGE NON RECONNU, LE TEXTE FRANÇAIS EST CONSERVÉ";
  }
  return `[TEST] ${requirement.source}`;
}

export async function buildPacks() {
  const testPack = await readJson("locales/test.json");
  const model = await readJson("locales/template.json");

  model.meta = {
    languageCode: "ewo",
    languageName: "Ewondo (modèle à remplir)",
    version: 3,
    status: "draft",
    validatedBy: [],
    validatedAt: null
  };
  testPack.meta.version = 3;

  for (const requirement of PACK_REQUIREMENTS) {
    const base = { requiredSlots: [...requirement.requiredSlots] };
    if (requirement.direction) base.direction = requirement.direction;
    testPack.templates[requirement.id] = { status: "test", ...base, text: testText(requirement), source: requirement.source };
    const existing = model.templates[requirement.id];
    model.templates[requirement.id] = {
      status: existing?.status ?? "draft",
      ...base,
      text: existing?.text ?? "",
      source: requirement.source
    };
  }

  await writeFile(new URL("locales/test.json", root), `${JSON.stringify(testPack, null, 2)}\n`);
  await writeFile(new URL("locales/template.json", root), `${JSON.stringify(model, null, 2)}\n`);
  await writeFile(
    new URL("core/locale-test-pack.js", root),
    moduleSource("TEST_PACK", testPack, [
      "Copy of locales/test.json as an ES module, so the content script can load it",
      "through the existing web_accessible_resources entry (core/*.js) without",
      "widening the manifest. Generated by `npm run packs:build`; a test keeps both identical.",
      "This pack is artificial: every text starts with [TEST]. It is not a language."
    ])
  );
  return { testPack, model };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { model } = await buildPacks();
  const ewoModule = new URL("core/locale-ewo-pack.js", root);
  let shipped = null;
  try {
    shipped = await readFile(ewoModule, "utf8");
  } catch {
    shipped = null;
  }
  // The shipped ewondo module is only replaced by install-ewo-pack.js once a
  // pack is validated; until then it is the draft model.
  if (!shipped || shipped.includes('"status": "draft"')) {
    await writeFile(
      ewoModule,
      moduleSource("EWO_PACK", model, [
        "Ewondo pack shipped with the extension. Generated file: do not edit by hand.",
        "Current content: the empty DRAFT model (no ewondo text is validated yet).",
        "The demo mode refuses it and the Nolia panel shows why.",
        "To ship a validated pack: npm run pack:ewo -- <path/to/ewo.json>"
      ])
    );
  }
  console.log(`Packs régénérés : ${Object.keys(model.templates).length} gabarits par pack.`);
}
